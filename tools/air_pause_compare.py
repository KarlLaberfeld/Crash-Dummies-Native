"""Run/compare the bounded native Air pause graphics candidate.

Reference captures are read-only comparison targets. Only the initial native
clock/timer/RNG header and raw per-display held buttons enter the probes; their
graphics geometry is generated by native gameplay. No poll/work/idle/edge/world
values from the original drive the candidate. Copy data is locally extracted.
"""
import argparse
import csv
import json
from pathlib import Path
import subprocess

from air_clock_compare import compare_states
from air_loop_timing import wait_active_cycles
from air_pause_access import analyze_accesses
from air_reference import write_json
from air_timing import elapsed_work
from reference_backend import require_capture_reference


def load(path):return json.loads(path.read_text(encoding='utf-8'))
def rows(path):
    with path.open(encoding='utf-8-sig',newline='') as stream:
        return [{k:v if k in ('phase','kind') else int(v) for k,v in row.items()} for row in csv.DictReader(stream)]


def paused_inputs(samples):
    if not samples or any(s['service']!=i for i,s in enumerate(samples)):
        raise ValueError('Missing/unordered display inputs')
    split=next((i for i,s in enumerate(samples) if s.get('displaySelector')==1),None)
    if split is None or split==0:raise ValueError('Requires selector-1 pause samples after native gameplay')
    end=split
    while end<len(samples) and samples[end].get('displaySelector')==1:end+=1
    if any(s.get('displaySelector')!=4 for s in samples[:split]):raise ValueError('Unexpected pre-pause display selector')
    return samples[:split],samples[split:end]


def compare_bus(original,prefix,native):
    if prefix.get('version')!=1 or len(prefix.get('objects',[]))!=40:
        raise ValueError('Missing native pause graphics prefix')
    pauses=original.get('pauses',[])
    if len(pauses)!=1:raise ValueError('Requires one complete original pause')
    source=pauses[0];objects=source.get('entryDmaSourceObjects',[])
    if len(objects)!=40:raise ValueError('Requires independently captured DMA-source geometry')
    entries=[p for p in source['points'] if p['pc']==0x1476]
    if len(entries)!=1:raise ValueError('Missing original pause-entry boundary')
    entry=entries[0];difference=[]
    for field,raw in (('scrollX','scx'),('scrollY','scy'),('windowX','wx'),('windowY','wy')):
        if prefix[field]!=entry['lcd'][raw]:difference.append(dict(owner=field,native=prefix[field],original=entry['lcd'][raw]))
    for i,(a,b) in enumerate(zip(prefix['objects'],objects)):
        if a['y']!=b['y'] or (b['y'] and a['x']!=b['x']):difference.append(dict(owner='geometry',slot=i,native=a,original=b))
    target=[e for e in source['bus'] if e['address']==0xff41 or 0x8000<=e['address']<0xa000]
    if not native or len(native)!=len(target):raise ValueError('Native bus events must cover the complete original pause')
    for i,(a,b) in enumerate(zip(native,target)):
        fields={}
        for field in ('phase','kind','address'):
            if a[field]!=b[field]:fields[field]=[a[field],b[field]]
        actual=a['cycle']-prefix['cycle'];expected=b['cycles']-entry['cycles']
        if actual!=expected:fields['relativeCycle']=[actual,expected]
        wanted_value=(b['data']&3) if a['address']==0xff41 else b['data']
        if a['value']!=wanted_value:fields['data']=[a['value'],wanted_value]
        if fields:difference.append(dict(owner='bus',event=i,fields=fields))
    return difference


def compare_graphics(original,prefix,native):
    source=original['pauses'][0].get('graphicsStates',[])
    owners=((0x1476,'enter'),(0x14b9,'wait'),(0x14dc,'restoreAudio'))
    if len(source)!=3 or len(native)!=3:raise ValueError('Missing accepted pause graphics read-back coverage')
    entry=source[0]['cycles'];differences=[]
    for (pc,name),a,b in zip(owners,native,source):
        if b.get('pc')!=pc or b.get('storageReadOwner')!='direct-vram-pause-v1' or a.get('phase')!=name:
            raise ValueError('Missing/reordered/unreadable graphics read-back owner')
        if len(b.get('statusRow',[]))!=20 or len(b.get('font',[]))!=128:
            raise ValueError('Incomplete pause graphics storage')
        fields={}
        actual=a['cycle']-prefix['cycle'];expected=b['cycles']-entry
        if actual!=expected:fields['relativeCycle']=[actual,expected]
        for field,target in (('status',b['statusRow']),('font',b['font'])):
            for i,value in enumerate(target):
                key=field+str(i)
                if key not in a:raise ValueError('Missing native graphics byte')
                if a[key]!=value:fields[key]=[a[key],value]
        if fields:differences.append(dict(phase=name,fields=fields))
    return differences


def compare(args):
    manifest=load(args.capture/'capture-summary.json');trace=load(args.capture/'trace.json')
    inputs=load(args.inputs);lcd=load(args.lcd);timing=load(args.timing)
    if manifest.get('controlDifferences') or not manifest.get('pauseReached'):raise ValueError('Requires a control-verified original pause')
    for data in (inputs,lcd,timing):
        require_capture_reference(manifest,data)
        if any(data.get(k)!=manifest.get(k) for k in ('romSha256','controlMemorySha256')):raise ValueError('Mixed original controls')
    audit=analyze_accesses(lcd,timing)
    if audit['sourceMismatches']:raise ValueError('Original source/access audit is incomplete')
    before,paused=paused_inputs(inputs['samples']);prefix=load(args.out/'graphics.json')
    native_states=rows(args.out/'states.csv');native_bus=rows(args.out/'bus.csv')
    state_differences=compare_states(trace['post'],native_states)
    if len(native_states)!=manifest['pauseAfter'] or prefix['updates']!=len(native_states) or prefix['displayServices']!=len(before):
        raise ValueError('Incomplete native pre-pause coverage')
    bus_differences=compare_bus(lcd,prefix,native_bus)
    graphics_differences=compare_graphics(lcd,prefix,rows(args.out/'bus.csv.graphics.csv'))
    source=timing['pauses'][0];entry=source['points'][0]['cycles'];interrupts=source['interrupts']
    original_services=[r for r in interrupts if r['kind']=='vblank'];native_services=rows(args.out/'bus.csv.services.csv')
    if len(native_services)!=len(paused) or len(paused)!=len(original_services):raise ValueError('Incomplete paused services/input samples')
    service_differences=[]
    for i,(a,b,buttons) in enumerate(zip(native_services,original_services,paused)):
        wanted=dict(service=i,tick=b['tick'],held=buttons['held'],pressed=buttons['pressed'],display=160,effects=64,music=60)
        fields={k:[a[k],v] for k,v in wanted.items() if a[k]!=v}
        if a['cycle']-prefix['cycle']!=b['start']-20-entry:
            fields['relativeCycle']=[a['cycle']-prefix['cycle'],b['start']-20-entry]
        if fields:service_differences.append(dict(service=i,fields=fields))
    expected=[];copies=source['copies'];points=source['points']
    for name,c in zip(('copy0','copy1','copy2','copy3'),copies):expected.append((name,c['start'],c['end'],elapsed_work(c['start'],c['end'],interrupts)))
    for i,p in enumerate(points[:-1]):
        q=points[i+1];name=p['name'];active=elapsed_work(p['cycles'],q['cycles'],interrupts)
        if name=='wait':
            stat=sum(r['kind']=='stat' and p['cycles']<=r['start']-20 and r['end']+16<=q['cycles'] for r in interrupts)
            active=wait_active_cycles(stat)
        if name in ('script','wait','wake','restoreAudio','return'):expected.append((name,p['cycles'],q['cycles'],active))
    expected.sort(key=lambda e:e[1]);native_phases=rows(args.out/'bus.csv.phases.csv')
    if len(expected)!=len(native_phases):raise ValueError('Incomplete native pause intervals')
    phase_differences=[]
    for i,(a,(name,start,end,work)) in enumerate(zip(native_phases,expected)):
        wanted=dict(phase=name,start=start-entry,end=end-entry,work=work)
        actual=dict(phase=a['phase'],start=a['start']-prefix['cycle'],end=a['end']-prefix['cycle'],work=a['work'])
        fields={k:[actual[k],v] for k,v in wanted.items() if actual[k]!=v}
        if fields:phase_differences.append(dict(interval=i,fields=fields))
    result=dict(comparedPrefixUpdates=len(native_states),comparedBusEvents=len(native_bus),comparedPausedServices=len(native_services),
        comparedPauseIntervals=len(native_phases),stateDifferences=state_differences,busDifferences=bus_differences,
        serviceDifferences=service_differences,phaseDifferences=phase_differences,graphicsDifferences=graphics_differences,
        comparedGraphicsStorageBytes=3*(20+128),productionPauseAccepted=False,
        evidenceLimit='Bounded independent-reference candidate and relative pause-entry comparison. No original modes, work, idle, worlds or edges drive native scheduling. Initial LCD-on phase, arbitrary IRQ acceptance, line-135 fetch cancellation, full pixels/PCM, audio software state, production integration and hardware remain open.')
    write_json(args.out/'comparison.json',result);print(json.dumps(result,indent=2))
    if any(result[k] for k in ('stateDifferences','busDifferences','serviceDifferences','phaseDifferences','graphicsDifferences')):
        raise ValueError('Native pause candidate differs from independent reference')


def run(args):
    args.out.mkdir(parents=True,exist_ok=True)
    manifest=load(args.capture/'capture-summary.json');trace=load(args.capture/'trace.json');inputs=load(args.inputs)
    require_capture_reference(manifest,inputs)
    if manifest.get('controlDifferences') or any(inputs.get(k)!=manifest.get(k) for k in ('romSha256','controlMemorySha256')):
        raise ValueError('Requires matching control-verified display samples')
    before,paused=paused_inputs(inputs['samples'])
    # Only the original initial phase seed and raw held buttons are inputs.
    # Dummy update rows supply comparison scope, never source update clocks.
    header=(args.capture/'inputs.txt').read_text().splitlines()[0]
    (args.out/'inputs.txt').write_text(header+'\n'+'0 0\n'*len(trace['pre']))
    (args.out/'buttons.txt').write_text(''.join(str(s['held'])+'\n' for s in before))
    (args.out/'paused-buttons.txt').write_text(''.join(str(s['held'])+'\n' for s in paused))
    with (args.out/'states.csv').open('w') as stream:
        subprocess.run([str(args.clock_probe.resolve()),str(args.out/'inputs.txt'),str(args.out/'services.csv'),str(manifest['difficulty']),
            '--display-inputs',str(args.out/'buttons.txt'),'--pause-entry',str(args.out/'graphics.json')],stdout=stream,check=True)
    p=load(args.out/'graphics.json')
    (args.out/'graphics.txt').write_text(f"{p['cycle']} {p['scrollX']} {p['windowX']} {p['windowY']} {p['tick']} {p['inputHeld']} {p['inputPrevious']} {p['pendingEffect']}\n"+
        '\n'.join(f"{o['x']} {o['y']}" for o in p['objects'])+'\n'+' '.join(str(v) for v in p['hudRow'])+'\n')
    subprocess.run([str(args.pause_probe.resolve()),str(args.out/'graphics.txt'),str(args.out/'bus.csv'),str(args.out/'paused-buttons.txt')],check=True)
    compare(args)


